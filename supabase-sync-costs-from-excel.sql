matched AS (
  SELECT DISTINCT ON (p.id)
    p.id AS product_id,
    e.sale_usd,
    e.cost_usd,
    e.margin_pct,
    COALESCE((SELECT value::numeric FROM public.app_settings WHERE key = 'exchange_rate' LIMIT 1), 1350) AS current_rate
  FROM public.products p
  JOIN excel_items e
    ON p.id = e.excel_id
    OR lower(trim(p.name)) = lower(trim(e.prod_name))
)
INSERT INTO public.product_costs (product_id, cost_usd, cost_ars, profit_margin, dollar_rate_key, cost_currency, updated_at)
SELECT
  m.product_id,
  m.cost_usd,
  ROUND(m.cost_usd * m.current_rate),
  m.margin_pct,
  'dolar1',
  'USD',
  NOW()
FROM matched m
ON CONFLICT (product_id) DO UPDATE SET
  cost_usd = EXCLUDED.cost_usd,
  cost_ars = EXCLUDED.cost_ars,
  profit_margin = EXCLUDED.profit_margin,
  cost_currency = 'USD',
  updated_at = NOW();
